-- Run in Supabase > SQL Editor. Existing location_points table is retained.
create table if not exists public.saved_places (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 name text not null check (char_length(name) between 1 and 50),
 latitude double precision not null check (latitude between -90 and 90),
 longitude double precision not null check (longitude between -180 and 180),
 radius_m integer not null default 100 check (radius_m between 30 and 1000),
 created_at timestamptz not null default now()
);
alter table public.saved_places enable row level security;
drop policy if exists "Users can view their own saved places" on public.saved_places;
create policy "Users can view their own saved places" on public.saved_places for select to authenticated using (auth.uid()=user_id);
drop policy if exists "Users can add their own saved places" on public.saved_places;
create policy "Users can add their own saved places" on public.saved_places for insert to authenticated with check (auth.uid()=user_id);
drop policy if exists "Users can delete their own saved places" on public.saved_places;
create policy "Users can delete their own saved places" on public.saved_places for delete to authenticated using (auth.uid()=user_id);
do $$
begin
 if to_regclass('public.location_points') is null then
  raise exception 'public.location_points must exist before enabling realtime.';
 end if;
 if not exists (select 1 from pg_publication where pubname='supabase_realtime') then
  raise exception 'Supabase publication supabase_realtime was not found.';
 end if;
 if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='location_points') then
  execute 'alter publication supabase_realtime add table public.location_points';
 end if;
end
$$;
